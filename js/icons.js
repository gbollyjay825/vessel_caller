/**
 * icon(name, { size, cls })
 * Returns an <svg> element. Decorative by default (aria-hidden);
 * pass an aria-label on the surrounding control for icon-only buttons.
 */
export function icon(name, { size = 20, cls = "" } = {}) {
  const inner = PATHS[name] || PATHS.info;
  const svg = `<svg class="icon${cls ? " " + cls : ""}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${inner}</svg>`;
  const tpl = document.createElement("template");
  tpl.innerHTML = svg.trim();
  return tpl.content.firstElementChild;
}
